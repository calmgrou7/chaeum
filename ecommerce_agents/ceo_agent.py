"""
채움(Chaeum) 이커머스 멀티 에이전트 시스템 - CEO(대표이사) 에이전트
MD와 마케팅팀의 제안을 검토하고 최종 의사결정을 내립니다.
"""
import anthropic

from .base_agent import BaseAgent
from .tools import CEO_TOOLS

# ──────────────────────────────────────────────────────────────
# CEO 에이전트 시스템 프롬프트
# ──────────────────────────────────────────────────────────────
CEO_SYSTEM_PROMPT = """
당신은 연 매출 100억원 규모 이커머스 쇼핑몰 **채움(Chaeum)**의 대표이사(CEO)입니다.
15년간 이커머스 산업에 종사하며 연 매출 100억원 규모의 쇼핑몰을 직접 성장시켰습니다.
결단력 있고 데이터 중심적이지만, 팀원들의 의견을 존중하는 리더십을 발휘합니다.

## 회사 정보
- 회사명: 채움(Chaeum)
- 연 매출: 100억원 (YoY +30% 성장 중)
- 월 매출 목표: 9억원 (연말 기준)
- 직원: 15명 (MD 3명, 마케팅 4명, 운영 5명, CS 3명)
- 비전: "합리적인 가격에 삶을 채우는 라이프스타일 쇼핑몰"

## 나의 역할
- MD팀과 마케팅팀의 제안을 검토하고 최종 의사결정
- 회사 전략 방향성 설정 및 유지
- 투자 예산 승인/조정
- KPI 목표 설정 및 성과 관리
- 팀 간 협업 조율 및 시너지 창출

## 의사결정 기준 (중요도 순)

### 상품 승인 기준
1. **마진율**: 순마진 40% 이상 필수 (40~50% 양호, 50%+ 우수)
2. **시장성**: 트렌드 점수 7점 이상
3. **경쟁력**: 차별화 포인트 명확히 존재
4. **리스크**: 초기 투자 최소화, MOQ 50개 이하 선호
5. **마케팅 가능성**: SNS 바이럴 가능성 고려

### 마케팅 승인 기준
1. **ROAS**: 최소 300% 이상
2. **예산 효율**: 채널별 비용 대비 효과 최적화
3. **타겟 명확성**: 타겟 세그먼트가 구체적이어야 함
4. **실행 가능성**: 현실적인 타임라인과 실행 계획

### 사업 기준
- 연 100억 매출 유지/성장
- 영업이익률 15% 이상
- 신규 상품 월 3~5개 론칭
- 히트상품 (월 1,000만원+ 매출) 분기 1개 이상 발굴

## 커뮤니케이션 스타일
- 직접적이고 명확한 의사결정
- "왜"에 대한 근거를 항상 제시
- 팀원의 노력을 인정하되 비즈니스 기준으로 평가
- 개선점을 구체적으로 제시
- 긍정적인 것은 적극 칭찬

## CEO로서 결정 표현 방식
- 승인: "✅ 승인합니다. 이유: ..."
- 조건부 승인: "⚡ 조건부 승인. 수정 후 진행: ..."
- 반려: "❌ 이번엔 반려. 이유: ... 다음에 이 부분을 보완해주세요."
- 마케팅 지시: "📢 마케팅팀 지시사항: ..."

항상 한국어로 응답하고, CEO답게 명확하고 결단력 있게 의사결정하세요.
모든 결정에는 비즈니스 근거를 제시하고, 팀원들이 성장할 수 있는 피드백을 주세요.
"""


class CEOAgent(BaseAgent):
    """
    CEO 에이전트.
    MD 기획서 검토 → 마케팅팀 지시 → 최종 사업 계획 승인을 수행합니다.
    """

    def __init__(
        self,
        client: anthropic.Anthropic,
        on_tool_call=None,
    ) -> None:
        super().__init__(
            client=client,
            role_name="CEO(대표이사)",
            system_prompt=CEO_SYSTEM_PROMPT,
            tools=CEO_TOOLS,
            on_tool_call=on_tool_call,
        )

    def review_md_proposals(self, md_proposals: str) -> str:
        """
        MD 팀의 상품 기획서를 검토하고 마케팅팀에 지시사항을 내립니다.

        Args:
            md_proposals: MD 에이전트가 작성한 상품 기획서

        Returns:
            CEO 검토 의견 + 마케팅팀 지시사항
        """
        self.reset_history()
        prompt = f"""
[MD팀 상품 기획서 보고]
{md_proposals}

MD팀이 이번 시즌 상품 기획서를 제출했습니다.
다음 순서로 검토해주세요:

1. 각 상품에 대해 **evaluate_business_metrics** 또는 **calculate_margin_analysis** 도구로
   사업성을 수치로 검증하세요.

2. 각 상품을 개별 평가하세요 (승인/조건부승인/반려 + 근거).

3. 최종 승인/조건부승인 상품 목록을 정리하고, 마케팅팀에 전달할 **마케팅 방향 지시서**를 작성하세요.

마케팅 방향 지시서 양식:
---
## 📋 마케팅팀 지시사항

### 이번 시즌 전략 방향
[전략 방향 설명]

### 론칭 대상 상품
| 상품명 | 판매가 | 마진율 | 마케팅 예산 한도 | 론칭 우선순위 |
|--------|--------|--------|----------------|-------------|

### 상품별 마케팅 포커스
**[상품1]**:
- 타겟:
- 핵심 메시지 방향:
- 추천 채널:
- 월 매출 목표:

**[상품2]**:
(동일 양식)

### 전체 예산 한도
- 이번 시즌 총 마케팅 예산: KRW X,XXX,XXX
- ROAS 최소 기준: X배

### 주의사항 및 금지사항
---

반려 상품에 대해서는 MD팀에게 개선 방향을 명확히 피드백해주세요.
"""
        return self.chat(prompt)

    def make_final_decision(
        self,
        md_proposals: str,
        marketing_plans: str,
        ceo_initial_review: str,
    ) -> str:
        """
        MD 기획서 + 마케팅 기획서를 종합 검토하여 최종 사업 계획을 결정합니다.

        Args:
            md_proposals: MD 상품 기획서
            marketing_plans: 마케팅팀 기획서
            ceo_initial_review: CEO 1차 검토 의견

        Returns:
            최종 사업 계획서 + 실행 지시
        """
        prompt = f"""
이제 MD팀 기획서와 마케팅팀 기획서를 모두 검토했습니다.
최종 사업 계획을 결정해주세요.

[MD 상품 기획서 요약]
{md_proposals[:2000]}...

[마케팅팀 기획서 요약]
{marketing_plans[:2000]}...

[내 1차 검토 의견]
{ceo_initial_review[:1000]}...

다음 항목을 포함한 **최종 사업 계획서**를 작성해주세요:

1. **최종 론칭 승인 상품 목록** (우선순위 포함)
2. **각 상품별 사업 목표** (월 매출, 마진, 판매량)
3. **전체 투자 계획** (소싱비 + 마케팅비 + 운영비)
4. **예상 수익 시뮬레이션** (도구 활용)
5. **론칭 타임라인** (D-Day 기준)
6. **팀별 실행 과제**
   - MD팀:
   - 마케팅팀:
   - 운영팀:
7. **리스크 및 대응 방안**
8. **성과 점검 일정**

마지막으로 팀원들에게 격려 메시지와 함께 이번 시즌의 핵심 목표를 공유해주세요.
"""
        return self.chat(prompt)

    def set_quarterly_direction(self, quarter: str, context: str = "") -> str:
        """
        분기 사업 방향을 설정하고 MD/마케팅팀에 오리엔테이션 브리핑을 합니다.

        Args:
            quarter: 분기 (예: "2025 Q2")
            context: 시장 상황, 이전 분기 실적 등 컨텍스트

        Returns:
            분기 오리엔테이션 브리핑 (텍스트)
        """
        self.reset_history()
        prompt = f"""
{quarter} 시즌이 시작되었습니다.
{f"참고 컨텍스트: {context}" if context else ""}

MD팀과 마케팅팀에 전달할 **{quarter} 분기 오리엔테이션 브리핑**을 작성해주세요:

1. 이번 분기 시장 환경 분석 (트렌드, 소비자 동향)
2. 채움(Chaeum) 이번 분기 목표 (매출, 신규 상품, KPI)
3. MD팀 소싱 방향 (주목할 카테고리, 소싱 기준 강조사항)
4. 마케팅팀 방향 (주력 채널, 마케팅 전략 포커스)
5. 팀 간 협업 포인트
6. 대표이사의 메시지

현재 날짜 기준 트렌드와 시장 상황을 반영하여 현실적으로 작성해주세요.
"""
        return self.chat(prompt)
