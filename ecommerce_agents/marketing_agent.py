"""
채움(Chaeum) 이커머스 멀티 에이전트 시스템 - 마케팅팀장 에이전트
신규 상품 마케팅 전략 수립, 채널별 캠페인 기획, KPI 설정을 담당합니다.
"""
import anthropic

from .base_agent import BaseAgent
from .tools import MARKETING_TOOLS

# ──────────────────────────────────────────────────────────────
# 마케팅 에이전트 시스템 프롬프트
# ──────────────────────────────────────────────────────────────
MARKETING_SYSTEM_PROMPT = """
당신은 연 매출 100억원 규모 이커머스 쇼핑몰 **채움(Chaeum)**의 마케팅팀장입니다.
디지털 마케팅 8년 경력을 보유하고 있으며, ROI 중심의 데이터 드리븐 마케팅으로 유명합니다.

## 회사 정보
- 회사명: 채움(Chaeum)
- 연 매출: 100억원 (월 평균 8.3억원)
- 월 마케팅 예산: 5,000만원~1억원
- 주요 고객층: 20~40대 여성 (메인), 30~40대 남성 (서브)
- 주요 플랫폼: 인스타그램, 네이버, 카카오, 유튜브, 틱톡

## 나의 역할
- 신규 상품 런칭 마케팅 전략 수립
- SNS 채널 (인스타그램, 틱톡, 유튜브) 운영 전략
- 네이버 쇼핑/파워링크 광고 최적화
- 카카오 비즈니스 채널 마케팅
- 인플루언서 마케팅 기획 및 집행
- CRM 마케팅 (재구매율 향상)
- 시즌/트렌드 기반 프로모션 기획

## 채널별 전략 전문성

### 인스타그램
- 릴스(Reels): 15~30초 제품 언박싱, 사용법, ASMR
- 피드: 감성 비주얼 + 간결한 카피
- 스토리: 설문, 투표, 한정 프로모션
- 쇼핑 태그 활용 직접 구매 유도

### 네이버
- 스마트스토어 SEO 최적화 (상품명, 태그, 상세페이지)
- 파워링크 광고 (브랜드/카테고리 키워드)
- 네이버 쇼핑 광고 (CPC/CPA 최적화)
- 검색광고 + 쇼핑 패키지

### 카카오
- 카카오채널 친구톡 (재구매 타겟)
- 카카오모먼트 디스플레이 광고
- 카카오쇼핑 입점 프로모션

### 인플루언서
- 나노 인플루언서 (1만~10만): 진정성, 낮은 비용
- 마이크로 인플루언서 (10만~50만): 적절한 도달
- 미디 인플루언서 (50만~): 브랜드 인지도

### 틱톡/유튜브 쇼츠
- 바이럴 콘텐츠 기획
- 챌린지 마케팅
- 리뷰/언박싱 콘텐츠

## KPI 기준
- **ROAS**: 최소 300% (목표 400~500%)
- **CPC**: 카테고리 벤치마크 대비 20% 낮게
- **전환율**: 업계 평균 2% 이상 (목표 3~5%)
- **재구매율**: 30% 이상
- **CAC(고객획득비용)**: 상품 가격의 20% 이하

## 예산 배분 원칙 (신규 상품 기준)
- 네이버 쇼핑 광고: 30~40%
- 인스타그램/메타: 25~30%
- 인플루언서: 20~25%
- 카카오: 10~15%
- 콘텐츠 제작비: 5~10%

## 보고 형식
마케팅 기획서 제출 시 반드시 포함:
1. 캠페인명 + 기간
2. 타겟 세그먼트 정의
3. 채널별 전략 및 예산 배분
4. 핵심 메시지 + 광고 카피
5. KPI 목표 (ROAS, 전환율, 매출 목표)
6. 인플루언서 활용 계획
7. 콘텐츠 캘린더 요약
8. 예상 ROI 계산 (도구 활용)

항상 한국어로 응답하고, 실행 가능한 구체적인 계획을 수립하세요.
데이터 기반 근거를 제시하고 예산 효율을 최우선으로 고려하세요.
"""


class MarketingAgent(BaseAgent):
    """
    마케팅팀장 에이전트.
    CEO 지시 + MD 제안 상품을 기반으로 채널별 마케팅 전략을 수립합니다.
    """

    def __init__(
        self,
        client: anthropic.Anthropic,
        on_tool_call=None,
    ) -> None:
        super().__init__(
            client=client,
            role_name="마케팅팀장",
            system_prompt=MARKETING_SYSTEM_PROMPT,
            tools=MARKETING_TOOLS,
            on_tool_call=on_tool_call,
        )

    def create_marketing_plans(
        self,
        ceo_direction: str,
        product_proposals: str,
    ) -> str:
        """
        CEO 방향성과 MD 제안 상품을 받아 마케팅 기획서를 작성합니다.

        Args:
            ceo_direction: CEO의 마케팅 방향 지시
            product_proposals: MD가 제안한 상품 기획서

        Returns:
            마케팅 기획서 (텍스트)
        """
        self.reset_history()
        prompt = f"""
[MD 상품 기획서]
{product_proposals}

[CEO 마케팅 방향 지시]
{ceo_direction}

위 정보를 바탕으로 각 승인 예정 상품에 대한 마케팅 기획서를 작성해주세요.

진행 순서:
1. **search_web** 도구로 각 상품 카테고리의 마케팅 트렌드와 경쟁사 광고 전략을 조사하세요.
   (예: "인스타그램 홈데코 마케팅 전략 2024", "네이버 쇼핑 광고 뷰티 성공 사례")

2. 각 상품별로 **calculate_marketing_roi** 도구로 예산 대비 예상 수익을 계산하세요.

3. 상품별 마케팅 기획서를 아래 양식으로 작성하세요:

---
## 📣 마케팅 기획서: [상품명]

### 캠페인 개요
- **캠페인명**:
- **캠페인 기간**: X주
- **총 예산**: KRW X,XXX,XXX
- **목표 ROAS**: X.X배
- **예상 매출**: KRW X,XXX,XXX

### 타겟 세그먼트
- **메인 타겟**:
- **서브 타겟**:
- **타겟 키워드**:

### 핵심 메시지
- 메인 카피:
- 서브 카피:
- 해시태그:

### 채널별 전략 및 예산
| 채널 | 전략 | 예산 | 기대 효과 |
|------|------|------|-----------|
| 인스타그램 | | | |
| 네이버 쇼핑 | | | |
| 카카오 | | | |
| 인플루언서 | | | |

### 인플루언서 계획
- **인플루언서 유형**: 나노/마이크로/미디
- **계약 조건**:
- **기대 노출**:

### KPI 목표
- ROAS:
- 전환율:
- 클릭율(CTR):
- 월 판매 목표:
- 재구매율 목표:

### ROI 계산 결과 (도구 기반)
[도구 결과 삽입]
---

각 상품에 대해 CEO의 방향성을 최대한 반영하여 작성하세요.
"""
        return self.chat(prompt)

    def refine_plans(self, ceo_feedback: str, original_plans: str) -> str:
        """
        CEO 피드백을 반영하여 마케팅 기획서를 수정합니다.

        Args:
            ceo_feedback: CEO의 수정 요청
            original_plans: 원본 마케팅 기획서

        Returns:
            수정된 마케팅 기획서
        """
        prompt = f"""
[원본 마케팅 기획서]
{original_plans}

[CEO 수정 요청]
{ceo_feedback}

CEO의 피드백을 반영하여 마케팅 기획서를 수정해주세요.
변경된 내용은 ✏️ 표시로 명확히 나타내주세요.
"""
        return self.chat(prompt)

    def create_launch_checklist(self, approved_plan: str) -> str:
        """
        최종 승인된 마케팅 플랜의 실행 체크리스트를 작성합니다.

        Args:
            approved_plan: 최종 승인된 마케팅 기획서

        Returns:
            실행 체크리스트
        """
        prompt = f"""
[최종 승인 마케팅 기획서]
{approved_plan}

위 기획서를 실행하기 위한 **D-Day 체크리스트**를 작성해주세요:

- D-30 (론칭 30일 전): 준비 사항
- D-14 (론칭 2주 전): 광고 소재 준비
- D-7 (론칭 1주 전): 사전 마케팅
- D-Day (론칭 당일): 실행 사항
- D+7 (론칭 1주 후): 성과 점검
- D+30 (론칭 1개월 후): KPI 리뷰

각 단계별로 담당자, 액션 아이템, 체크 포인트를 명시해주세요.
"""
        return self.chat(prompt)
