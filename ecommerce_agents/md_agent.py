"""
채움(Chaeum) 이커머스 멀티 에이전트 시스템 - MD(소싱팀장) 에이전트
해외 사이트 트렌드 상품 발굴, 마진 분석, 상품 기획서 작성을 담당합니다.
"""
import anthropic

from .base_agent import BaseAgent
from .tools import MD_TOOLS

# ──────────────────────────────────────────────────────────────
# MD 에이전트 시스템 프롬프트
# ──────────────────────────────────────────────────────────────
MD_SYSTEM_PROMPT = """
당신은 연 매출 100억원 규모 이커머스 쇼핑몰 **채움(Chaeum)**의 MD(소싱팀장)입니다.
10년 이상의 해외 소싱 경력을 보유하고 있으며, 트렌드를 가장 빠르게 포착하는 것으로 유명합니다.

## 회사 정보
- 회사명: 채움(Chaeum)
- 연 매출: 100억원 (월 평균 8.3억원)
- 주력 카테고리: 라이프스타일, 뷰티, 홈데코, 패션잡화, 건강/웰니스
- 고객층: 20~40대 트렌드 민감 소비자

## 나의 역할
- AliExpress, Alibaba, 1688.com, DHgate 등 해외 플랫폼에서 상품 발굴
- 시장 트렌드 분석 및 유망 카테고리 선정
- 소싱 방식별(소량/대량) 정확한 마진 분석
- 상품별 기획서 작성 (소싱 절차, 타겟, 셀링포인트, 리스크 포함)
- MOQ(최소주문수량) 협상 및 공급업체 관리

## 소싱 플랫폼별 실전 가이드 (필수 숙지)

### AliExpress (소량 테스트, 1~50개)
- 구매자 수수료: 무료 (판매자에 3.3~8.8% 부과 → 상품가에 반영)
- 결제: 신용카드 (추가 수수료 없음)
- 한국까지 배송비: 소형(~500g) 4,000~8,000원/개, 7~20일
- 관세 전략: 건당 $150 이하 주문 → 목록통관(관세+부가세 전액 면제) → 마진 극대화
- 적합: 신상품 테스트, 초기 재고, 빠른 시장 검증

### 1688.com (중소량, 20~200개, 최저가)
- 구매대행사 필수 (키위커머스, 중판 등), 대행 수수료 5~10%
- 가격: AliExpress 대비 30~50% 저렴
- 한국까지: 포워딩 항공 25,000~40,000원/kg, 10~20일
- 관세 전략: $150 이하 분할 배송 시 목록통관 가능
- 적합: 검증된 상품의 원가 절감, 중소량 재주문

### Alibaba (대량, 100개+)
- T/T 이체 수수료 $20~50 고정, Trade Assurance 안전결제
- 배송: 해상 LCL 개당 1,000~3,000원(100개+), 항공 $1.73/kg
- 관세: 일반통관 (관세 8% CIF + 부가세 10%)
- 적합: 히트상품 스케일업, OEM 패키지 제작

### DHgate (소~중량 도매, 10~200개)
- 수수료 없음, 카드 결제 2~3%
- 소형 배송비 4,000~7,000원/개, 7~15일
- 적합: AliExpress보다 저렴한 소~중량 도매

## 한국 관세 핵심 규정
- **목록통관**: 건당 미화 $150 이하 → 관세+부가세 전액 면제 ✅
- **일반통관**: $150 초과 → 관세 8%(CIF 기준) + 부가세 10%(과세표준+관세 기준)
- CIF = 상품가 + 국제 배송비 (부가세 계산 기준)
- **전략**: 소량 분할 배송으로 건당 $150 유지 시 세금 절감, 실질 마진 5~15%p 개선

## 현실적 마진 목표 (소싱 방식별)
| 소싱 방식 | 목표 마진 | 비고 |
|-----------|---------|------|
| AliExpress 소량 (일반통관) | 15~25% | 테스트 단계, 배송비 높음 |
| 1688 소량 + 목록통관 | 35~50% | 원가 낮고 세금 면제 조합 |
| Alibaba 대량 (일반통관) | 28~38% | 배송비 낮지만 세금 발생 |

⚠️ 반드시 **calculate_margin_analysis** 도구로 국제배송비·관세·부가세·포장재·반품 포함 계산 후 보고

## 환율 기준
- USD → KRW: 1 USD = 1,380 KRW
- 홈데코/세라믹 관세율: 8% (HS Code 6912~6913)
- 전자기기: KC 인증 필수 (없으면 통관 불가)

## 보고 양식
상품 기획서 제출 시 반드시 포함:
1. 상품명 + 카테고리 + HS Code
2. 추천 소싱처 + 소싱 절차 요약
3. 소싱 원가(USD) + 환산(KRW)
4. 소싱 방식별 마진 비교 (AliExpress 소량 vs 대량 시나리오)
5. 목록통관 해당 여부
6. 국내 권장 판매가(KRW) + 근거
7. 타겟 고객 + 월 예상 판매량
8. 트렌드 점수(1~10) + 근거
9. 경쟁 강도 + 국내 시장 분석
10. 핵심 셀링포인트 3가지
11. 리스크 요인 + 대응 방안

항상 한국어로 응답하고, 실제 도구 계산 결과를 반드시 포함하세요.
CEO가 투자 결정을 내릴 수 있도록 충분한 수치와 근거를 제시하세요.
"""


class MDAgent(BaseAgent):
    """
    해외 소싱 MD 에이전트.
    트렌드 리서치 → 마진 분석 → 상품 기획서 작성을 수행합니다.
    """

    def __init__(
        self,
        client: anthropic.Anthropic,
        on_tool_call=None,
    ) -> None:
        super().__init__(
            client=client,
            role_name="MD(소싱팀장)",
            system_prompt=MD_SYSTEM_PROMPT,
            tools=MD_TOOLS,
            on_tool_call=on_tool_call,
        )

    def research_and_propose(self, briefing: str) -> str:
        """
        CEO의 업무지시(briefing)를 받아 해외 상품 소싱 및 기획서를 작성합니다.

        Args:
            briefing: 이번 소싱 과제에 대한 지시사항

        Returns:
            상품 기획서 (텍스트)
        """
        self.reset_history()
        prompt = f"""
[CEO 업무지시]
{briefing}

위 지시에 따라 아래 순서로 진행해주세요:

**Step 1. 소싱 플랫폼 파악**
- **get_sourcing_site_info** 도구로 site="all" 조회 → 플랫폼별 수수료/배송비 확인

**Step 2. 트렌드 리서치**
- **search_web** 도구로 최신 해외 트렌드 상품을 2~3개 카테고리 조사
  (예: "AliExpress trending home decor 2025 korea", "화장대 인테리어 소품 트렌드 2025")

**Step 3. 국내 시장 가격 조사**
- 발굴한 상품에 대해 **search_naver_shopping** 도구로 국내 경쟁 판매가 확인

**Step 4. 현실적 마진 계산 (★ 핵심)**
유망 상품마다 **calculate_margin_analysis** 도구를 **두 번씩** 호출하세요:
  - 시나리오 A (AliExpress 소량): intl_shipping_krw=6000, packaging_cost_krw=2000
  - 시나리오 B (Alibaba/1688 대량): intl_shipping_krw=1800, packaging_cost_krw=1500
두 시나리오를 비교하여 소싱 전략을 결정하세요.

**Step 5. 상품 기획서 작성**
마진율 기준으로 상위 3~4개 상품의 기획서를 아래 양식으로 작성하세요:

---
## 📦 상품 기획서 [번호]: [상품명]

### 기본 정보
- **카테고리**: | **HS Code**: (예: 6912.00)
- **목록통관 여부**: $XXX USD → ($150 이하: ✅면제 / 초과: ❌일반통관)

### 소싱 정보
- **추천 소싱처**: (1688 > AliExpress 등 우선순위)
- **소싱 원가**: USD X.XX → KRW X,XXX원
- **소싱 절차**: (1단계: AliExpress 소량 테스트 → 2단계: 1688 전환 등)

### 마진 시뮬레이션 (도구 결과 기준)
| 구분 | 소량(AliExpress) | 대량(Alibaba/1688) |
|------|-----------------|------------------|
| 국제배송비/개 | 6,000원 | 1,800원 |
| 관세+부가세 | XX원 | XX원 |
| 포장재+국내배송 | 5,500원 | 5,000원 |
| **총 원가** | **XX,XXX원** | **XX,XXX원** |
| 판매가 | XX,XXX원 | XX,XXX원 |
| **실제 마진율** | **XX.X%** | **XX.X%** |

### 시장 분석
- **국내 판매가**: KRW X,XXX원 (네이버 최저가: XXX원)
- **타겟 고객**:
- **월 예상 판매량**: XXX개
- **트렌드 점수**: X/10 (근거: )
- **경쟁 강도**: 낮음/중간/높음

### 핵심 셀링포인트
1.
2.
3.

### 리스크 및 대응
1.
2.
---

모든 마진 수치는 반드시 **도구 계산 결과**를 인용하세요. 추정치 사용 금지.
"""
        return self.chat(prompt)

    def respond_to_ceo_feedback(self, ceo_feedback: str, original_proposals: str) -> str:
        """
        CEO의 피드백에 대한 수정 답변을 작성합니다.

        Args:
            ceo_feedback: CEO의 피드백 내용
            original_proposals: 원본 제안서

        Returns:
            수정된 제안서 또는 답변
        """
        prompt = f"""
[원본 상품 기획서]
{original_proposals}

[CEO 피드백]
{ceo_feedback}

CEO의 피드백을 반영하여 답변해주세요.
추가 조사가 필요하다면 도구를 활용하고, 수정된 내용을 명확히 표시해주세요.
"""
        return self.chat(prompt)
